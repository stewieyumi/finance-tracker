import { randomBytes } from "node:crypto";
import { OAuth2Client } from "google-auth-library";
import { readFinanceSession, usesFinanceSession } from "../server/financeSession.js";
import { AppleCalendarError, connectAppleCalendar, getAppleCalendars, pushAppleEvent, readAppleEvents, setupAppleCalendars } from "../server/appleCalendar.js";
import { calendarStore, calendarUserKey, deleteAppleConnection, parseAppleCredentials, publicAppleConnection, readAppleConnection, saveAppleConnection } from "../server/appleCalendarConnection.js";
import { GIG_CALENDAR_GROUPS } from "../src/utils/gigStatus.js";
import { isCalendarGig, type AppleCalendarEvent } from "../src/utils/appleCalendar.js";
import type { VercelApiRequest, VercelApiResponse } from "./notion.js";

const google = new OAuth2Client();
export const maxDuration = 60;

export default async function handler(req: VercelApiRequest, res: VercelApiResponse) {
  res.setHeader("Cache-Control", "no-store");
  if (req.method !== "POST") return res.status(405).json({ error: "Method not allowed." });
  if (req.headers["sec-fetch-site"] && req.headers["sec-fetch-site"] !== "same-origin") {
    return res.status(403).json({ error: "Open Calendar sync from Finance Tracker." });
  }

  try {
    // The verified app user owns the connection. No Apple account or owner ID from the request can select another record.
    let sub: string;
    if (usesFinanceSession(req)) {
      const profile = await readFinanceSession(req);
      if (!profile?.sub) return res.status(401).json({ error: "Please reconnect your Finance Tracker account." });
      sub = profile.sub;
    } else {
      const authorization = req.headers.authorization;
      const credential = typeof authorization === "string" ? authorization.replace(/^Bearer\s+/i, "") : "";
      if (!credential || credential.length > 8192) return res.status(401).json({ error: "Please sign in to Finance Tracker." });
      const audience = process.env.VITE_GOOGLE_CLIENT_ID;
      if (!audience) throw new AppleCalendarError("Finance Tracker sign-in has not been configured.", 503);
      const payload = await google.verifyIdToken({ idToken: credential, audience })
        .then(ticket => ticket.getPayload()).catch(() => undefined);
      if (!payload?.sub || !payload.email_verified) return res.status(401).json({ error: "Please reconnect your Finance Tracker account." });
      sub = payload.sub;
    }
    if ((typeof req.body === "string" ? req.body.length : JSON.stringify(req.body ?? null).length) > 64000) {
      return res.status(413).json({ error: "This Calendar request is too large." });
    }
    const body = typeof req.body === "string" ? JSON.parse(req.body) : req.body;
    if (!body || !["status", "connect", "disconnect", "preview", "setup", "push", "pull"].includes(body.action)) {
      return res.status(400).json({ error: "Choose a Calendar sync action." });
    }
    const credentials = body.action === "connect" ? parseAppleCredentials(body) : null;
    if (body.action === "connect" && !credentials) {
      return res.status(400).json({ error: "Enter your Apple Account email and the 16-letter app-specific password generated by Apple." });
    }
    if (body.action !== "status" && body.connectionId !== null &&
        (typeof body.connectionId !== "string" || !/^[a-f0-9]{32}$/.test(body.connectionId))) {
      return res.status(400).json({ error: "Refresh your calendar connection before continuing." });
    }
    if (body.action === "push" && !isCalendarGig(body.gig)) {
      return res.status(400).json({ error: "Set a valid title, date, booking status, and completion state before syncing." });
    }
    const expected = body.expected as AppleCalendarEvent | null;
    if (["push", "pull"].includes(body.action) && (expected !== null && (
      !expected || typeof expected.uid !== "string" || !expected.uid || expected.uid.length > 1000 ||
      typeof expected.etag !== "string" || !expected.etag || expected.etag.length > 1000 ||
      !Object.hasOwn(GIG_CALENDAR_GROUPS, expected.group) || !isCalendarGig(expected.gig)
    ))) return res.status(400).json({ error: "Refresh the Calendar review before applying changes." });
    if (body.action === "pull" && !expected) return res.status(400).json({ error: "Choose a calendar event." });
    if (body.action === "push" && expected && expected.gig.id !== body.gig.id) {
      return res.status(400).json({ error: "The selected gig does not match this calendar event." });
    }

    const redis = calendarStore();
    const userKey = calendarUserKey(sub);
    if (body.action === "status") {
      try {
        return res.status(200).json({ connection: publicAppleConnection(await readAppleConnection(redis, sub)) });
      } catch (error) {
        if (error instanceof AppleCalendarError && error.status === 409) {
          return res.status(200).json({ connection: null, reconnectRequired: true });
        }
        throw error;
      }
    }
    // Serialize connection changes, reads and remote writes so a disconnect/reconnect cannot cross an in-flight sync.
    const lockKey = "ft_apple_calendar_lock:" + userKey;
    const lockToken = randomBytes(16).toString("hex");
    if (!await redis.set(lockKey, lockToken, { nx: true, ex: 60 })) {
      throw new AppleCalendarError("Another Calendar action is running. Try again in a moment.", 409);
    }
    try {
      let connection;
      try { connection = await readAppleConnection(redis, sub); } catch (error) {
        if (error instanceof AppleCalendarError && error.status === 409 && ["connect", "disconnect"].includes(body.action)) {
          connection = null;
        } else throw error;
      }
      if (body.connectionId !== (connection?.id ?? null)) {
        throw new AppleCalendarError("Your calendar connection changed. Close this review and reopen it.", 409);
      }
      if (body.action === "disconnect") {
        await deleteAppleConnection(redis, sub);
        return res.status(200).json({ connection: null });
      }
      const signal = AbortSignal.timeout(40000);
      if (body.action === "connect") {
        // Limit password verification attempts independently of the short-lived operation lock.
        const attemptsKey = `ft_apple_connect_attempts:${userKey}:${Math.floor(Date.now() / 900000)}`;
        const attempts = await redis.incr(attemptsKey);
        if (attempts === 1) await redis.expire(attemptsKey, 1800);
        if (attempts > 10) throw new AppleCalendarError("Too many connection attempts. Try again in 15 minutes.", 429);
        // Validate against Apple before replacing a working connection. No events are written on connect.
        const client = await connectAppleCalendar(signal, credentials!);
        await getAppleCalendars(client);
        const saved = await saveAppleConnection(redis, sub, credentials!);
        return res.status(200).json({ connection: publicAppleConnection(saved) });
      }
      if (!connection) return res.status(409).json({ error: "Connect your iCloud account to continue.", connectionRequired: true });
      const client = await connectAppleCalendar(signal, { username: connection.username, password: connection.password });
      const calendars = await getAppleCalendars(client);
      if (body.action === "preview") {
        const { events, skipped } = await readAppleEvents(client, calendars);
        return res.status(200).json({
          connectionId: connection.id,
          events: events.map(({ object: _object, ...event }) => event),
          skipped,
          missingCalendars: Object.entries(GIG_CALENDAR_GROUPS)
            .filter(([group]) => !calendars[group as keyof typeof calendars]).map(([, definition]) => definition.name),
        });
      }
      if (body.action === "pull") {
        const { events } = await readAppleEvents(client, calendars);
        const current = events.find(event => event.uid === expected!.uid);
        if (!current || current.etag !== expected!.etag || current.group !== expected!.group) {
          throw new AppleCalendarError("The calendar event changed. Refresh the review before importing it.", 409);
        }
        return res.status(200).json({ gig: current.gig });
      }
      if (body.action === "setup") await setupAppleCalendars(client);
      else await pushAppleEvent(client, calendars, body.gig, expected);
      return res.status(200).json({ success: true });
    } finally {
      await redis.eval("if redis.call('GET', KEYS[1]) == ARGV[1] then return redis.call('DEL', KEYS[1]) end return 0", [lockKey], [lockToken]).catch(() => {});
    }
  } catch (error) {
    if (error instanceof SyntaxError) return res.status(400).json({ error: "Invalid Calendar request." });
    // Provider/store errors may contain authorization headers or credentials. Return only controlled messages.
    return res.status(error instanceof AppleCalendarError ? error.status : 503)
      .json({ error: error instanceof AppleCalendarError ? error.message : "iCloud sync is unavailable. Refresh the review and try again." });
  }
}
