import { test, expect, returningData, storedData, navigate } from './fixtures';

test('new-user setup, wallet creation, and expense deduction survive reopening', async ({ page, isolatedApp }) => {
  const app = await isolatedApp();
  await page.getByRole('button', { name: 'Get Started' }).click();
  await page.getByRole('spinbutton', { name: 'Gross Salary' }).fill('24000');
  await page.getByRole('button', { name: 'Next: Wallets' }).click();
  await page.getByRole('button', { name: 'Next: Milestone Goal' }).click();
  await page.getByRole('textbox', { name: 'Goal Name' }).fill('Browser Goal');
  await page.getByRole('spinbutton', { name: 'Target Amount' }).fill('10000');
  await page.getByRole('button', { name: 'Next: Appearance' }).click();
  await page.getByRole('button', { name: 'Finish Setup & Launch' }).click();
  await navigate(page, 'Wallets');
  await page.getByRole('button', { name: 'Add New Account' }).click();
  await page.getByRole('combobox', { name: 'Account Name' }).fill('Travel Cash');
  await page.getByRole('button', { name: 'Save Account' }).click();
  await expect.poll(async () => (await storedData(page))?.settings?.customWallets?.some(wallet => wallet.label === 'Travel Cash')).toBe(true);
  await page.getByRole('button', { name: /Main Account/ }).first().click();
  const balance = page.getByRole('dialog', { name: 'Edit Balance' });
  await balance.getByRole('spinbutton', { name: 'Balance' }).fill('1000');
  await balance.getByRole('button', { name: 'Save Balance' }).click();
  await navigate(page, 'Expenses');
  await page.getByRole('button', { name: /^Manual\b/ }).click();
  const expense = page.getByRole('dialog', { name: 'Log Expense' });
  await expense.getByRole('spinbutton', { name: 'Amount (₱)' }).fill('125');
  await expense.getByRole('textbox', { name: 'Merchant / Name' }).fill('Browser Coffee');
  await expense.getByRole('button', { name: 'Save & Deduct' }).click();
  await expect(expense).toBeHidden();
  await expect.poll(async () => (await storedData(page))?.wallets.main).toBe(875);
  await app.waitForSaved();
  await page.reload();
  await navigate(page, 'Wallets');
  await expect(page.getByRole('heading', { name: 'Total Wallet Balance' })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Total Wallet Balance' })).toContainText('₱875.00');
  await expect.poll(async () => (await storedData(page))?.wallets.main).toBe(875);
  expect((await storedData(page))?.library.expenses).toEqual([expect.objectContaining({ merchant: 'Browser Coffee', amount: 125 })]);
});

test('transfer principal moves between wallets while only its fee reduces the total', async ({ page, isolatedApp }) => {
  const app = await isolatedApp(returningData());
  await navigate(page, 'Wallets');
  await page.getByRole('button', { name: 'Transfer', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Transfer', exact: true });
  await dialog.getByRole('spinbutton', { name: 'Amount', exact: true }).fill('250');
  await dialog.getByRole('combobox', { name: 'From', exact: true }).selectOption('main');
  await dialog.getByRole('combobox', { name: 'To', exact: true }).selectOption('cash');
  await dialog.getByRole('button', { name: 'Add transfer fee' }).click();
  await dialog.getByRole('spinbutton', { name: 'Transfer fee (₱)' }).fill('5');
  await dialog.getByRole('button', { name: 'Transfer', exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect.poll(async () => (await storedData(page))?.wallets).toEqual({ main: 1745, cash: 350 });
  await app.waitForSaved();
  await page.reload();
  await navigate(page, 'Wallets');
  await expect.poll(async () => (await storedData(page))?.wallets).toEqual({ main: 1745, cash: 350 });
  await expect(page.getByRole('region', { name: 'Total Wallet Balance' })).toContainText('₱2,095.00');
  const data = await storedData(page);
  expect(data?.library.manualTransactions).toEqual([expect.objectContaining({ type: 'transfer', amount: 250, transferFee: 5 })]);
  expect(Object.values(data!.wallets).reduce((sum, amount) => sum + amount, 0)).toBe(2095);
});

test('inflow cancellation preserves data and name-only entry remains editable', async ({ page, isolatedApp }) => {
  const app = await isolatedApp(returningData());
  await navigate(page, 'Operations');
  await page.getByRole('button', { name: 'Inflows', exact: true }).click();
  const opener = page.getByRole('button', { name: /Add New Inflow/i });
  await opener.click();
  let dialog = page.getByRole('dialog', { name: 'Add New Inflow' });
  await expect(dialog.getByRole('textbox', { name: 'Inflow Name' })).toBeFocused();
  await dialog.getByRole('textbox', { name: 'Inflow Name' }).fill('Discard this draft');
  await page.keyboard.press('Escape');
  await expect(dialog).toBeHidden();
  await expect(opener).toBeFocused();
  expect((await storedData(page))?.library.receivables).toEqual([]);
  await opener.click();
  dialog = page.getByRole('dialog', { name: 'Add New Inflow' });
  await dialog.getByRole('textbox', { name: 'Inflow Name' }).fill('Future project');
  await dialog.getByRole('button', { name: 'Add Inflow', exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect.poll(async () => (await storedData(page))?.library.receivables.length).toBe(1);
  expect((await storedData(page))?.wallets).toEqual({ main: 2000, cash: 100 });
  await app.waitForSaved();
  await page.reload();
  await navigate(page, 'Operations');
  await page.getByRole('button', { name: 'Inflows', exact: true }).click();
  const row = page.locator('[data-testid^="receivable-"]').filter({ hasText: 'Future project' }).filter({ visible: true });
  await expect(row).toContainText('—');
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Edit Inflow' });
  await expect(edit.getByRole('spinbutton', { name: 'Gross Amount' })).toHaveValue('');
  await page.keyboard.press('Escape');
  await expect(edit).toBeHidden();
});
