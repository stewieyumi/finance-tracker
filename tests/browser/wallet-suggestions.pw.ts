import { test, expect, returningData, storedData, navigate } from './fixtures';
for (const theme of ['light', 'dark'] as const) test(`wallet prefix suggestions and beginner budget help in ${theme}`, async ({ page, isolatedApp }, info) => {
  const data = returningData(); data.settings = { ...data.settings, theme };
  await isolatedApp(data); const snapshot = await storedData(page);
  await navigate(page, 'Wallets');
  await page.getByRole('button', { name: 'Add New Account', exact: true }).click();
  const input = page.getByRole('combobox', { name: 'Account Name', exact: true });
  await input.fill('g');
  await expect(page.getByRole('listbox', { name: 'Wallet name suggestions' })).toBeVisible();
  await expect(page.getByRole('listbox', { name: 'Wallet name suggestions' }).getByRole('option')).toHaveText(['GCash', 'GoTyme']);
  await page.screenshot({ path: info.outputPath(`suggestions-${theme}.png`) });
  const option = page.getByRole('option', { name: 'GCash', exact: true });
  if (info.project.name === 'phone') await option.tap(); else await option.click();
  await expect(input).toHaveValue('GCash');
  expect(await storedData(page)).toEqual(snapshot);
  await input.fill('G'); await input.press('ArrowDown'); await input.press('ArrowDown'); await input.press('Enter');
  await expect(input).toHaveValue('GoTyme');
  await input.fill('Personal jar'); await expect(page.getByRole('listbox')).toHaveCount(0);
  await page.getByRole('form', { name: 'Add wallet', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click();
  await navigate(page, 'Dashboard'); await page.getByRole('button', { name: /^Budget Plan/ }).click();
  const dialog = page.getByRole('dialog', { name: 'Budget Plan', exact: true });
  await expect(dialog.getByText('How to start', { exact: true })).toBeVisible();
  await dialog.getByText('How to start', { exact: true }).click();
  await expect(dialog).toContainText('Paid expenses already reflected in your balances should not be subtracted again.');
  await expect(dialog).toContainText('Starting daily guide =');
  await dialog.getByRole('button', { name: 'Build my budget' }).click();
  const setup = page.getByRole('dialog', { name: 'Budget setup', exact: true });
  await expect(setup.getByRole('heading', { name: 'Which money can you use?' })).toBeVisible();
  await setup.getByRole('button', { name: 'Close budget setup' }).click();
  await dialog.getByRole('button', { name: 'Close budget plan' }).click();
  expect(await storedData(page)).toEqual(snapshot);
});
